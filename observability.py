def setup_sentry(component="web"):
    """Initialise Sentry if a DSN is configured. Returns True when enabled.

    A NOTE ON HOSTING. sentry.io is a foreign SaaS and this platform is deployed
    inside Iran, where reaching it is unreliable and where sending user traffic
    metadata abroad may not be acceptable. Sentry's server is open source, and
    GlitchTip speaks the same protocol in a fraction of the footprint — either
    can be run on the same VPS and pointed at with SENTRY_DSN. Nothing here
    assumes the hosted service.

    With no DSN this is a silent no-op, so a deployment that does not want error
    tracking simply leaves the variable empty."""
    dsn = (os.environ.get("SENTRY_DSN") or "").strip()
    if not dsn:
        return False
    try:
        import sentry_sdk
        from sentry_sdk.integrations.logging import LoggingIntegration
    except ImportError:
        get_logger().warning("SENTRY_DSN is set but sentry-sdk is not installed")
        return False

    integrations = [LoggingIntegration(level=logging.INFO,        # breadcrumbs
                                       event_level=logging.ERROR)]  # events
    try:
        if component == "web":
            from sentry_sdk.integrations.flask import FlaskIntegration
            integrations.append(FlaskIntegration())
        else:
            from sentry_sdk.integrations.celery import CeleryIntegration
            integrations.append(CeleryIntegration())
    except ImportError:
        pass

    sentry_sdk.init(
        dsn=dsn,
        environment=os.environ.get("APP_ENV", "development"),
        release=os.environ.get("APP_RELEASE") or None,
        integrations=integrations,
        # OFF. With it on the SDK attaches cookies, the request body and the
        # user's IP to every event — exactly the three things this module exists
        # to keep out of the record.
        send_default_pii=False,
        traces_sample_rate=float(os.environ.get("SENTRY_TRACES_SAMPLE_RATE", "0")),
        before_send=_scrub_event,
        max_breadcrumbs=30,
    )
    sentry_sdk.set_tag("component", component)
    return True


def _scrub_event(event, hint):
    """Last line of defence before an event leaves the process.

    send_default_pii=False already prevents most of this; doing it again here
    means a future integration that collects something new cannot leak it by
    default."""
    req = event.get("request") or {}
    headers = req.get("headers") or {}
    for name in list(headers):
        if name.lower() in _REDACTED_HEADERS:
            headers[name] = "[redacted]"
    # The query string carries the Persian filter values and search terms.
    req.pop("query_string", None)
    req.pop("data", None)
    req.pop("cookies", None)
    if req:
        event["request"] = req
    # Keep the numeric id for correlation, drop everything that identifies.
    user = event.get("user") or {}
    event["user"] = {"id": user.get("id")} if user.get("id") else {}
    return event


