def init_app(flask_app):
    """Attach request-id handling and the slow-request warning to a Flask app.

    Replaces the _perf_start/_perf_log pair that printed
    `[perf] GET /stocks -> 200 4231ms`."""
    from flask import g, request

    setup_logging()
    log = get_logger("boursenegar.request")

    @flask_app.before_request
    def _start_request():
        # nginx sets X-Request-ID from its own $request_id, so the id in the
        # nginx access log and the id in these records are the same string.
        g._request_id = set_request_id(request.headers.get("X-Request-ID"))
        g._t0 = time.perf_counter()

    @flask_app.after_request
    def _finish_request(response):
        t0 = getattr(g, "_t0", None)
        if t0 is None:
            return response
        ms = (time.perf_counter() - t0) * 1000.0
        rid = getattr(g, "_request_id", None)
        if rid:
            # Hand the id back so a user reporting a problem can quote it.
            response.headers["X-Request-ID"] = rid

        # The 200 ms threshold from order 00, kept as the order requires — but
        # as a structured warning-level event rather than a printed line.
        slow = ms >= SLOW_REQUEST_MS
        if slow or response.status_code >= 500:
            log.warning(
                "slow request" if slow else "request failed",
                extra={
                    "http_method": request.method,
                    # PATH only. The query string holds the Persian filter
                    # values, the search term and the watchlist ticker.
                    "http_path": request.path,
                    "status": response.status_code,
                    "duration_ms": round(ms, 1),
                    "threshold_ms": SLOW_REQUEST_MS,
                    "endpoint": request.endpoint,
                    "user_id": _current_user_id(),
                },
            )
        return response

    @flask_app.teardown_request
    def _clear_request(exc=None):
        _request_id.set(None)

    return flask_app


def _current_user_id():
    """The numeric id only — never the username or e-mail."""
    try:
        from flask_login import current_user
        if getattr(current_user, "is_authenticated", False):
            return getattr(current_user, "id", None)
    except Exception:
        pass
    return None
